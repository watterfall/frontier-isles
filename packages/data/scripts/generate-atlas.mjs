import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { FRONTIERS } from '../src/frontiers.ts';
import { INTERIORS } from '../src/interiors.ts';
import { INTERIORS_2 } from '../src/interiors-2.ts';

/**
 * Emits TWO browser-safe L0 files, split by when the browser actually needs
 * the bytes:
 *
 * - `atlas.ts`        — everything the L0 map needs to PAINT: positions,
 *                       titles, domain, cluster (the map groups by it), scores
 *                       (the sea projection reads them), stage/members/activity.
 *                       apps/web loads this eagerly, so the first frame is a
 *                       real map with no round trip. That is the resilience
 *                       rule: the readable twin ships with the app.
 * - `atlas-detail.ts` — `brief` and `citation`: card prose and the reference
 *                       shelf, shown only after the visitor opens something.
 *                       Together they were 41.9% of the old atlas.ts, in the
 *                       entry chunk, downloaded by every visitor before the
 *                       first pixel. The API does not carry them (ApiIsland has
 *                       neither field), so they stay static — just deferred.
 *
 * The split is by TIMING, not by availability: apps/web merges the detail into
 * island state right after mount, and every consumer already renders these two
 * fields conditionally, so the pre-merge frame is correct rather than empty.
 */
const atlasPath = fileURLToPath(new URL('../src/atlas.ts', import.meta.url));
const detailPath = fileURLToPath(new URL('../src/atlas-detail.ts', import.meta.url));
const check = process.argv.includes('--check');
const interiorSlugs = new Set([
  ...Object.keys(INTERIORS),
  ...Object.keys(INTERIORS_2),
]);

const entries = FRONTIERS.map((frontier) => ({
  id: frontier.id,
  atlasN: frontier.atlasN,
  slug: frontier.slug,
  title: frontier.title,
  qfocus: frontier.qfocus,
  domain: frontier.domain,
  cluster: frontier.cluster,
  scores: frontier.scores,
  stage: frontier.stage,
  members: frontier.members,
  activity: frontier.activity,
  ...(frontier.dormant === undefined ? {} : { dormant: frontier.dormant }),
  ...(frontier.outlier === undefined ? {} : { outlier: frontier.outlier }),
  ...(frontier.resolved === undefined ? {} : { resolved: frontier.resolved }),
  chart: frontier.chart,
  hasInterior: interiorSlugs.has(frontier.slug),
}));

const detail = Object.fromEntries(
  FRONTIERS.map((frontier) => [
    frontier.slug,
    {
      ...(frontier.brief === undefined ? {} : { brief: frontier.brief }),
      ...(frontier.citation === undefined ? {} : { citation: frontier.citation }),
    },
  ]).filter(([, value]) => Object.keys(value).length > 0),
);

const atlasSource = `/**
 * GENERATED by scripts/generate-atlas.mjs — do not edit by hand.
 *
 * This is the browser-safe L0 projection of FRONTIERS. Deep editorial content
 * and station interiors intentionally live behind the L1 data entry points.
 *
 * Card prose (\`brief\`) and the reference shelf (\`citation\`) live in the
 * sibling \`atlas-detail.ts\`, which apps/web loads after first paint — see the
 * header of scripts/generate-atlas.mjs for why the split runs along that line.
 */
import type { FrontierEntry } from './frontiers';

export type FrontierAtlasEntry = Pick<FrontierEntry,
  | 'id'
  | 'atlasN'
  | 'slug'
  | 'title'
  | 'qfocus'
  | 'domain'
  | 'cluster'
  | 'scores'
  | 'stage'
  | 'members'
  | 'activity'
  | 'dormant'
  | 'outlier'
  | 'resolved'
  | 'chart'
> & { hasInterior: boolean };

export const FRONTIER_ATLAS: FrontierAtlasEntry[] = ${JSON.stringify(entries, null, 2)};

export const FRONTIER_ATLAS_BY_SLUG = new Map(
  FRONTIER_ATLAS.map((frontier) => [frontier.slug, frontier]),
);

export function frontierAtlasBySlug(slug: string): FrontierAtlasEntry | undefined {
  return FRONTIER_ATLAS_BY_SLUG.get(slug);
}
`;

const detailSource = `/**
 * GENERATED by scripts/generate-atlas.mjs — do not edit by hand.
 *
 * The deferred half of the L0 atlas: card prose and the reference shelf, keyed
 * by slug. Import this only from a dynamic \`import()\` — pulling it in eagerly
 * puts it back in the entry chunk and undoes the split.
 */
import type { FrontierEntry } from './frontiers';

export type FrontierAtlasDetail = Pick<FrontierEntry, 'brief' | 'citation'>;

export const FRONTIER_ATLAS_DETAIL: Record<string, FrontierAtlasDetail> = ${JSON.stringify(detail, null, 2)};
`;

const outputs = [
  { path: atlasPath, source: atlasSource, label: 'packages/data/src/atlas.ts' },
  { path: detailPath, source: detailSource, label: 'packages/data/src/atlas-detail.ts' },
];

if (check) {
  for (const { path, source, label } of outputs) {
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current !== source) {
      console.error(`${label} is stale. Run pnpm --filter @frontier-isles/data generate:atlas.`);
      process.exitCode = 1;
    }
  }
} else {
  for (const { path, source } of outputs) await writeFile(path, source);
  console.log(
    `Generated ${entries.length} Atlas summaries at packages/data/src/atlas.ts ` +
      `and ${Object.keys(detail).length} detail records at packages/data/src/atlas-detail.ts.`,
  );
}
