/**
 * Generates `src/literature.ts` — the per-island reference list projected from
 * the xfrontier atlas `evidence.json`, keyed by island slug.
 *
 * Why a generator and not hand-authored: these are provenance records, not
 * editorial prose. Every entry is a real, linkable source that already ships
 * with the atlas record the island was built from (`atlasN`); nothing here is
 * written by hand, so nothing here can be invented.
 *
 * Run:  node --experimental-strip-types scripts/generate-literature.mjs [evidence.json]
 * The default source path is the local xfrontier checkout. The OUTPUT is
 * committed, so neither CI nor a normal build needs that checkout present.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { FRONTIERS } from '../src/frontiers.ts';

const evidencePath = process.argv[2] ?? '/Users/jili/AIAI/frontier/audit/evidence.json';
const destination = fileURLToPath(new URL('../src/literature.ts', import.meta.url));

const evidence = JSON.parse(await readFile(evidencePath, 'utf8'));

/** Same URL modulo scheme/www/trailing slash. */
const norm = (u) => String(u ?? '').replace(/^https?:\/\/(www\.)?/, '').replace(/\/+$/, '').toLowerCase();

/** The identity keys for "is this the same paper as that one". URL alone is not
 * enough: the headline citation often links doi.org/10.1126/science.aad6253
 * while the evidence set links science.org/doi/10.1126/science.aad6253 — same
 * paper, different host, and the island would show it twice. So key on the DOI
 * when the URL carries one, and on the normalised title in every case. */
const doiOf = (u) => (String(u ?? '').match(/10\.\d{4,9}\/[^\s?#]+/) ?? [null])[0]?.toLowerCase() ?? null;
const titleKey = (t) => String(t ?? '').toLowerCase().replace(/[^a-z0-9一-龥]/g, '');
const keysOf = (title, url) => {
  const out = [`u:${norm(url)}`, `t:${titleKey(title)}`];
  const doi = doiOf(url);
  if (doi) out.push(`d:${doi}`);
  return out;
};

const byslug = {};
let kept = 0;
let skipped = 0;
for (const frontier of FRONTIERS) {
  const sources = evidence[String(frontier.atlasN)]?.sources ?? [];
  const list = [];
  const seen = new Set(keysOf(frontier.citation.title, frontier.citation.url));
  for (const s of sources) {
    // A reference without a title, a link, a venue or a year is not a citation
    // anyone can check, and an uncheckable citation is worse than none.
    if (!s?.title || !s?.url || !s?.venue || typeof s.year !== 'number') { skipped++; continue; }
    const keys = keysOf(s.title, s.url);
    if (keys.some((k) => seen.has(k))) { skipped++; continue; }
    for (const k of keys) seen.add(k);
    list.push({ title: s.title, venue: s.venue, year: s.year, url: s.url });
  }
  if (list.length > 0) { byslug[frontier.slug] = list; kept += list.length; }
}

const body = Object.entries(byslug)
  .map(([slug, list]) => `  ${JSON.stringify(slug)}: [\n${list
    .map((c) => `    { title: ${JSON.stringify(c.title)}, venue: ${JSON.stringify(c.venue)}, year: ${c.year}, url: ${JSON.stringify(c.url)} },`)
    .join('\n')}\n  ],`)
  .join('\n');

const source = `/**
 * GENERATED by scripts/generate-literature.mjs — do not edit by hand.
 *
 * Per-island reference lists projected from the xfrontier atlas evidence set,
 * deduplicated against each island's headline \`citation\`. Every entry is a
 * real, linkable source; entries missing a title, link, venue or year are
 * dropped rather than patched, because an uncheckable citation is worse than
 * none (§6 leavability: this travels with the island's problem.md).
 *
 * Browser consumers should load this entry point LAZILY — it belongs to the L1
 * island surface, not to the L0 atlas projection.
 */

export interface IslandReference {
  title: string;
  venue: string;
  year: number;
  url: string;
}

const LITERATURE_BY_SLUG: Record<string, IslandReference[]> = {
${body}
};

/** Real references for one island, or an empty list when the atlas record
 *  carried none beyond the headline citation. Never fabricated. */
export function literatureBySlug(slug: string): IslandReference[] {
  return LITERATURE_BY_SLUG[slug] ?? [];
}

/** Islands that currently carry at least one extra reference. */
export const LITERATURE_SLUGS: readonly string[] = Object.keys(LITERATURE_BY_SLUG);
`;

await writeFile(destination, source, 'utf8');
console.log(`literature.ts: ${Object.keys(byslug).length}/${FRONTIERS.length} islands · ${kept} references · ${skipped} dropped (dupe or incomplete)`);
