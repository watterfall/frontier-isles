test('an actual toy-model run returns to the trail without a required prediction', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' }); await launch(page);
  await page.getByRole('button', { name: '带着这个问题出发' }).click();
  await page.getByText('在一个可运行的模型里试一试', { exact: true }).click();
  await page.getByRole('button', { name: '同步：萤火虫、心肌与电网' }).click();
  const model = page.getByRole('dialog', { name: '亲手搭一个会跑的模型' });
  await model.getByRole('button', { name: '运行', exact: true }).click();
  await expect(model.getByText('这次是先观察，没有事前预测。可以带着读数提出下一次问题。')).toBeVisible();
  await model.getByRole('button', { name: '把这次运行放进考察札记' }).click();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog', { name: '领域碰撞' })).toBeVisible();
  await expect(page.getByText('模型观察', { exact: true })).toBeVisible();
  const notes = await page.evaluate(() => JSON.parse(localStorage.getItem('fi-collision-expeditions-v1')!).entries[0].notes);
  const receipt = JSON.parse(notes.find((n: any) => n.kind === 'model').attachment);
  expect(receipt.prediction).toBeNull(); expect(receipt.observation.steps).toBeGreaterThan(0); expect(receipt.observation.final).not.toBe(receipt.observation.initial);
});
