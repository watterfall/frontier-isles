test('curiosity branches and recovers without scores or required stages', async ({ page }) => {
  await launch(page); const dialog = page.getByRole('dialog', { name: '领域碰撞' });
  await expect(dialog.getByText('离线资料', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('navigation', { name: '跨领域主题' }).getByRole('button')).toHaveCount(6);
  await expect(dialog.getByText(/实践印记|继续下一步/)).toHaveCount(0);
  await dialog.getByRole('button', { name: '带着这个问题出发' }).click();
  await dialog.getByLabel('此刻，你想追问什么？').fill('相似可能来自测量滤波；先控制采样过程。');
  await dialog.getByRole('button', { name: '留下思考', exact: true }).click();
  await dialog.locator('.fi-collision-branches button').first().click();
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('fi-collision-expeditions-v1')!));
  expect(data.entries).toHaveLength(2); expect(data.entries[1].parentId).toBe(data.entries[0].id);
  expect(data.entries[0].source.datasetVersion).toBe(snapshot.datasetVersion);
  const downloaded = page.waitForEvent('download'); await dialog.getByRole('button', { name: '导出探索记录' }).click();
  expect((await downloaded).suggestedFilename()).toBe('frontier-expedition.md');
  await page.keyboard.press('Escape'); await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('button', { name: /领域碰撞/ }).first()).toBeFocused();
  await page.reload(); await page.getByRole('button', { name: /领域碰撞/ }).first().click();
  await expect(page.getByLabel('此刻，你想追问什么？')).toBeVisible();
  await page.getByRole('button', { name: '我的航迹', exact: true }).click();
  await expect(page.locator('.fi-collision-trail li')).toHaveCount(2);
  await page.locator('.fi-collision-trail button').first().click();
  await expect(page.getByText('相似可能来自测量滤波；先控制采样过程。', { exact: true })).toBeVisible();
});
